def check_slope_exists(source_entity_id: str) -> Optional[int]:
    """
    Check if a slope with the given OSM source_entity_id already exists.
    
    Returns the API slope ID if found, None otherwise.
    """
    try:
        time.sleep(REQUEST_DELAY)
        response = SESSION.get(SLOPES_ENDPOINT, headers=HEADERS, timeout=60)
        if response.status_code != 200:
            log.error("Failed to fetch slopes for existence check: %d", response.status_code)
            return None
        
        for slope in response.json():
            if slope.get("source", {}).get("entity_id") == source_entity_id:
                return slope["id"]
    except requests.RequestException as e:
        log.error("Error checking slope existence: %s", e)
    return None


