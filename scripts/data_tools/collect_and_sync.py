def create_or_update_slope(slope_data: dict, dry_run: bool = False) -> tuple[bool, str]:
    """
    Create a new slope or update an existing one via the API.
    
    Returns (success, message) tuple.
    """
    # Check if already exists
    existing_id = None
    if not dry_run:
        existing_id = check_slope_exists(slope_data["source_entity_id"])
    
    if existing_id:
        # Update existing slope
        if dry_run:
            return True, f"DRY RUN: Would update slope (existing_id={existing_id})"
        
        try:
            time.sleep(REQUEST_DELAY)
            url = f"{SLOPES_ENDPOINT}/{existing_id}"
            response = SESSION.put(url, json=slope_data, headers=HEADERS, timeout=30)
            if response.status_code == 200:
                return True, f"Updated slope {existing_id}"
            else:
                return False, f"Update failed: {response.status_code} - {response.text}"
        except requests.RequestException as e:
            return False, f"Update error: {e}"
    else:
        # Create new slope
        if dry_run:
            return True, "DRY RUN: Would create new slope"
        
        try:
            time.sleep(REQUEST_DELAY)
            response = SESSION.post(SLOPES_ENDPOINT, json=slope_data, headers=HEADERS, timeout=30)
            if response.status_code == 201:
                return True, f"Created slope (id={response.json()})"
            else:
                return False, f"Create failed: {response.status_code} - {response.text}"
        except requests.RequestException as e:
            return False, f"Create error: {e}"


