def build_node_map(elements: list[dict]) -> dict[int, tuple[float, float]]:
    """Build a map of node ID -> (lon, lat) from OSM elements."""
    node_map = {}
    for el in elements:
        if el.get("type") == "node":
            node_map[el["id"]] = (el["lon"], el["lat"])
    return node_map


def extract_geometry(element: dict, node_map: dict) -> tuple[list, Optional[float], Optional[float]]:
    """
    Extract geometry from an OSM way or relation.
    
    Returns:
        - List of [lon, lat] coordinate pairs
        - Direction (azimuth in degrees) if calculable
        - None values if geometry cannot be extracted
    """
    coords = []
    
    if element.get("type") == "way":
        for node_id in element.get("nodes", []):
            if node_id in node_map:
                coords.append(list(node_map[node_id]))
    
    elif element.get("type") == "relation":
        # For relations, collect all member way nodes
        member_nodes = []
        for member in element.get("members", []):
            if member.get("type") == "way" and member.get("ref") in node_map:
                member_nodes.append(node_map[member["ref"]])
        if member_nodes:
            coords = [list(n) for n in member_nodes]
    
    # Calculate direction (azimuth) from first and last points
    direction = None
    if len(coords) >= 2:
        lon1, lat1 = coords[0]
        lon2, lat2 = coords[-1]
        # Calculate bearing from start to end
        d_lon = math.radians(lon2 - lon1)
        lat1_rad = math.radians(lat1)
        lat2_rad = math.radians(lat2)
        x = math.sin(d_lon) * math.cos(lat2_rad)
        y = math.cos(lat1_rad) * math.sin(lat2_rad) - \
            math.sin(lat1_rad) * math.cos(lat2_rad) * math.cos(d_lon)
        bearing = math.atan2(x, y)
        direction = (math.degrees(bearing) + 360) % 360
    
    return coords, direction


def parse_osm_slope(element: dict, node_map: dict) -> Optional[dict]:
    """
    Parse an OSM slope element into a structured dict matching the API schema.
    
    Returns None if the element cannot be parsed.
    """
    tags = element.get("tags", {})
    
    # Skip if not a piste
    if "piste:type" not in tags:
        return None
    
    # Generate OSM ID string (e.g., "way/12345" or "relation/67890")
    osm_type = element.get("type", "unknown")
    osm_id = element.get("id")
    if osm_id is None:
        return None
    source_entity_id = f"{osm_type}/{osm_id}"
    
    # Extract geometry
    coords, direction = extract_geometry(element, node_map)
    
    # Get start/end coordinates
    lat_start = coords[0][1] if coords else None
    lon_start = coords[0][0] if coords else None
    lat_end = coords[-1][1] if coords else None
    lon_end = coords[-1][0] if coords else None
    
    # Map piste:difficulty to API difficulty values
    # OSM uses: novice, easy, intermediate, advanced, expert, freeride
    # API uses: green, blue, red, black, unknown
    osm_difficulty = tags.get("piste:difficulty", "unknown").lower().strip()
    difficulty_map = {
        "novice": "green",
        "easy": "green",
        "intermediate": "blue",
        "advanced": "red",
        "expert": "black",
        "freeride": "black",
        "extreme": "black",
    }
    difficulty = difficulty_map.get(osm_difficulty, "unknown")
    
    # Map piste:grooming to API grooming_status
    grooming = tags.get("piste:grooming", "").lower().strip()
    if grooming in ("yes", "daily", "frequently"):
        grooming_status = "groomed"
    elif grooming == "no":
        grooming_status = "ungroomed"
    elif grooming == "occasional":
        grooming_status = "partially groomed"
    else:
        grooming_status = "unknown"
    
    # Build path GeoJSON string
    path_geojson = None
    if coords:
        path_points = [{"latitude": c[1], "longitude": c[0]} for c in coords]
        path_geojson = json.dumps(path_points)
    
    # Normalize name (lowercase, stripped)
    name = tags.get("name", "").strip()
    name_normalized = name.lower().strip() if name else None
    
    return {
        # Required fields
        "resort_id": "unassigned",  # Placeholder: resort assignment done later
        "name": name if name else None,
        "difficulty": difficulty,
        
        # Optional fields from OSM tags
        "name_normalized": name_normalized,
        "length_m": None,  # Not available from OSM directly
        "vertical_drop_m": None,
        "average_gradient": None,
        "max_gradient": None,
        
        # Boolean flags - check for oneway, lit tags
        "snowmaking": False,  # Not directly available from OSM piste tags
        "night_skiing": tags.get("lit", "").lower() in ("yes", "true"),
        "family_friendly": False,  # Not directly available
        "race_slope": tags.get("piste:type") == "racing",  # Racing pistes
        
        # Geometry
        "lat_start": lat_start,
        "lon_start": lon_start,
        "lat_end": lat_end,
        "lon_end": lon_end,
        "slope_path_json": path_geojson,
        "direction": direction,
        
        # Source tracking
        "source_system": "osm",
        "source_entity_id": source_entity_id,
        
        # Status fields
        "operational_status": "unknown",
        "grooming_status": grooming_status,
        "operational_note": None,
        "status_updated_at": None,
        "status_source_url": None,
        
        # Metadata for tracking
        "_osm_type": osm_type,
        "_osm_id": osm_id,
    }


def parse_osm_lift(element: dict, node_map: dict) -> Optional[dict]:
    """
    Parse an OSM lift element into a structured dict matching the API schema.
    
    Returns None if the element cannot be parsed.
    """
    tags = element.get("tags", {})
    
    # Skip if not an aerialway
    if "aerialway" not in tags:
        return None
    
    # Generate OSM ID string
    osm_type = element.get("type", "unknown")
    osm_id = element.get("id")
    if osm_id is None:
        return None
    source_entity_id = f"{osm_type}/{osm_id}"
    
    # Extract geometry
    coords, _ = extract_geometry(element, node_map)
    
    # Get start/end coordinates
    lat_start = coords[0][1] if coords else None
    lon_start = coords[0][0] if coords else None
    lat_end = coords[-1][1] if coords else None
    lon_end = coords[-1][0] if coords else None
    
    # Map aerialway type to API lift_type
    # OSM uses: chair_lift, gondola, drag_lift, goodold_tow, magic_carpet, etc.
    # API uses: chairlift, gondola, draglift, t-bar, magic_carpet, cable_car, etc.
    aerialway = tags.get("aerialway", "unknown").lower().strip()
    lift_type_map = {
        "chair_lift": "chairlift",
        "gondola": "gondola",
        "drag_lift": "draglift",
        "goodold_tow": "draglift",
        "t-bar": "draglift",
        "magic_carpet": "magic_carpet",
        "cable_car": "cable_car",
        "funitel": "funitel",
        "mixed_lift": "mixed",
        "zip_line": "zip_line",
        "rope_tow": "draglift",
        "platter": "draglift",
        "button_lift": "draglift",
    }
    lift_type = lift_type_map.get(aerialway, aerialway)
    
    # Normalize name
    name = tags.get("name", "").strip()
    name_normalized = name.lower().strip() if name else None
    
    # Parse capacity if available
    capacity_per_hour = None
    try:
        capacity_str = tags.get("capacity:hourly", tags.get("capacity", ""))
        if capacity_str:
            capacity_per_hour = int(capacity_str)
    except (ValueError, TypeError):
        pass
    
    # Parse seats/occupancy
    seats = None
    try:
        seats_str = tags.get("seats", tags.get("occupancy", ""))
        if seats_str:
            seats = int(seats_str)
    except (ValueError, TypeError):
        pass
    
    # Check for bubble/heated seats
    bubble = tags.get("bubble", "").lower() in ("yes", "true", "1")
    heated_seats = tags.get("heated_seats", "").lower() in ("yes", "true", "1")
    
    return {
        # Required fields
        "resort_id": "unassigned",  # Placeholder: resort assignment done later
        "name": name if name else None,
        "lift_type": lift_type,
        
        # Optional fields
        "name_normalized": name_normalized,
        "capacity_per_hour": capacity_per_hour,
        "seats": seats,
        "bubble": bubble,
        "heated_seats": heated_seats,
        "year_built": None,  # Not available from OSM
        "altitude_start_m": None,  # Could be derived from elevation tags
        "altitude_end_m": None,
        
        # Geometry
        "lat_start": lat_start,
        "lon_start": lon_start,
        "lat_end": lat_end,
        "lon_end": lon_end,
        
        # Source tracking
        "source_system": "osm",
        "source_entity_id": source_entity_id,
        
        # Status fields
        "operational_status": "unknown",
        "operational_note": None,
        "planned_open_time": None,
        "planned_close_time": None,
        "status_updated_at": None,
        "status_source_url": None,
        
        # Metadata for tracking
        "_osm_type": osm_type,
        "_osm_id": osm_id,
    }


