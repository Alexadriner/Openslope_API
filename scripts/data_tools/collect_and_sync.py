def get_progress_file(instance_id: int) -> Path:
    """Return the path to the progress file for this worker instance."""
    return Path(PROGRESS_DIR) / f"progress_{instance_id}.json"


def load_progress(instance_id: int) -> dict:
    """Load progress state from file, or return default state."""
    progress_file = get_progress_file(instance_id)
    if progress_file.exists():
        try:
            with open(progress_file, "r") as f:
                return json.load(f)
        except (json.JSONDecodeError, IOError) as e:
            log.warning("Failed to load progress file: %s", e)
    return {
        "instance_id": instance_id,
        "lng_min": None,
        "lng_max": None,
        "last_processed_osm_id": None,
        "last_run_timestamp": None,
        "slopes_synced": 0,
        "lifts_synced": 0,
        "slopes_updated": 0,
        "lifts_updated": 0,
        "skipped": [],
    }


def save_progress(instance_id: int, progress: dict) -> None:
    """Save progress state to file."""
    progress_file = get_progress_file(instance_id)
    progress["last_run_timestamp"] = datetime.now(timezone.utc).isoformat()
    with open(progress_file, "w") as f:
        json.dump(progress, f, indent=2)


def clear_all_progress() -> None:
    """Clear all progress files."""
    progress_dir = Path(PROGRESS_DIR)
    for f in progress_dir.glob("progress_*.json"):
        f.unlink()
        log.info("Cleared progress file: %s", f.name)


