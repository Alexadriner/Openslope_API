def query_osm_slopes(bbox: dict) -> list[dict]:
    """
    Query Overpass API for all ski slopes (piste:type=*) within a bounding box.
    
    Returns a list of OSM elements with their tags and geometry.
    """
    query = f"""
    [out:json][timeout:{OVERPASS_TIMEOUT}];
    (
      way["piste:type"]({bbox['min_lat']},{bbox['min_lon']},{bbox['max_lat']},{bbox['max_lon']});
      relation["piste:type"]({bbox['min_lat']},{bbox['min_lon']},{bbox['max_lat']},{bbox['max_lon']});
    );
    out body;
    >;
    out skel qt;
    """
    try:
        time.sleep(REQUEST_DELAY)
        response = SESSION.post(OVERPASS_URL, data={"data": query}, timeout=OVERPASS_TIMEOUT + 30)
        response.raise_for_status()
        return response.json().get("elements", [])
    except requests.RequestException as e:
        log.error("Overpass query failed for slopes: %s", e)
        return []


