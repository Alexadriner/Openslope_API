def main():
    parser = argparse.ArgumentParser(
        description="Openslope OSM Data Collection Worker",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  # Run worker 1 for longitude range -180 to -144
  python collect_and_sync.py --instance-id 1 --lng-min -180 --lng-max -144

  # Dry run (preview without executing)
  python collect_and_sync.py --instance-id 1 --lng-min -180 --lng-max -144 --dry-run

  # Clear all progress files
  python collect_and_sync.py --clear
        """,
    )
    parser.add_argument(
        "--instance-id",
        type=int,
        required=True,
        help="Unique ID for this worker instance",
    )
    parser.add_argument(
        "--lng-min",
        type=float,
        required=True,
        help="Minimum longitude for this worker's range",
    )
    parser.add_argument(
        "--lng-max",
        type=float,
        required=True,
        help="Maximum longitude for this worker's range",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Preview API calls without executing them",
    )
    parser.add_argument(
        "--clear",
        action="store_true",
        help="Clear all progress files and exit",
    )
    
    args = parser.parse_args()
    
    if args.clear:
        clear_all_progress()
        log.info("All progress files cleared.")
        return
    
    # Validate longitude range
    if args.lng_min < -180 or args.lng_max > 180 or args.lng_min >= args.lng_max:
        log.error("Invalid longitude range: lng-min must be >= -180, lng-max must be <= 180, and lng-min < lng-max")
        sys.exit(1)
    
    run_worker(args.instance_id, args.lng_min, args.lng_max, args.dry_run)


if __name__ == "__main__":
    main()